"""WP4.8e (EST-21): the DMC batch on instantaneous range-rate observations.

WP4.8d fitted [r0, v0, w0] to position observations only.  The same fit now runs on
[range, range-rate, az, el] rows.  Oracles as in WP4.8d: observations generated by
the DMC dynamics themselves (the fit must recover r0, v0, w0), a central-difference
design matrix (independent of the STM) for the posterior, and a noisy NEES.  The
counted-Doppler physics, whose partials integrate over the count interval, is refused.
"""
from __future__ import annotations

from dataclasses import replace

import numpy as np
import pytest

from lunar_od.dmc import DMCOptions, propagate_dmc_state
from lunar_od.dmc_batch import estimate_position_dmc_batch, estimate_range_rate_dmc_batch
from lunar_od.estimators import _range_rate_residual_from_h, _range_rate_weight_diagonal
from lunar_od.measurements import compute_range_rate_residuals_analytic
from lunar_od.radiometrics import RangeRatePhysicsConfig
from tests.test_ekf_smoother import MU_MOON, _add_noise, _arc, _build_clean_range_rate_observations, _earth, _sun

TOL = dict(rtol=1e-12, atol=1e-13)
W_TRUE = np.array([3e-6, -2e-6, 1e-6])


def _dmc_arc(options, noise_seed=None, duration_s=3601.0):
    x_true0, t_pass, _, pass_geo, _ = _arc("range_rate", duration_s=duration_s)
    x9 = np.concatenate([x_true0, W_TRUE])
    truth = propagate_dmc_state(t_pass, x9, options, MU_MOON, 0.0, 0.0, _earth, _sun, stm=False, **TOL)
    obs = _build_clean_range_rate_observations(t_pass, truth[:, :6], pass_geo)
    if noise_seed is not None:
        obs = _add_noise(obs, "range_rate", np.random.default_rng(noise_seed))
    guess = np.concatenate([x_true0 + np.array([150.0, -80.0, 60.0, 0.05, -0.03, 0.02]), np.zeros(3)])
    return t_pass, obs, pass_geo, x9, guess


def _fit(t, obs, geo, guess, options, **kw):
    return estimate_range_rate_dmc_batch(t, obs, guess, geo, MU_MOON, 0.0, 0.0, _earth, _sun, options, **TOL, **kw)


@pytest.mark.parametrize("axes", ["inertial", "rtn"])
def test_noiseless_dmc_truth_is_recovered_from_range_rate(axes):
    options = DMCOptions(sigma_mps2=1e-3, tau_s=1800.0, axes=axes)
    t, obs, geo, x9, guess = _dmc_arc(options)
    x, status, _ = _fit(t, obs, geo, guess, options)
    assert status in {"Converged", "J-Stab"}
    assert np.linalg.norm(x[:3] - x9[:3]) < 1e-3
    assert np.linalg.norm(x[3:6] - x9[3:6]) < 1e-6
    np.testing.assert_allclose(x[6:], x9[6:], rtol=1e-3, atol=1e-11)


def test_range_rate_posterior_matches_a_finite_difference_design():
    options = DMCOptions(sigma_mps2=1e-5, tau_s=1800.0)
    t, obs, geo, _, guess = _dmc_arc(options, noise_seed=12)
    x, _, stats = _fit(t, obs, geo, guess, options, return_posterior=True)
    w = _range_rate_weight_diagonal(obs, geo)

    def residual(xx):
        hist = propagate_dmc_state(t, xx, options, MU_MOON, 0.0, 0.0, _earth, _sun, stm=False, **TOL)
        _, h_nom, _ = compute_range_rate_residuals_analytic(hist[:, :6], obs, geo)
        return _range_rate_residual_from_h(obs, h_nom)

    steps = [1.0] * 3 + [1e-3] * 3 + [1e-7] * 3          # as WP4.8d
    h = np.column_stack([-(residual(x + np.eye(9)[j] * s) - residual(x - np.eye(9)[j] * s)) / (2 * s)
                         for j, s in enumerate(steps)])
    prior = np.zeros((9, 9))
    prior[6:, 6:] = np.eye(3) / options.sigma_mps2**2
    info = h.T @ (w[:, None] * h) + prior
    d = np.sqrt(np.diag(info))
    reference = np.linalg.inv(info / d[:, None] / d[None, :]) / d[:, None] / d[None, :]
    np.testing.assert_allclose(np.sqrt(np.diag(stats.posterior_covariance)), np.sqrt(np.diag(reference)), rtol=1e-5)
    corr = lambda c: c / np.sqrt(np.outer(np.diag(c), np.diag(c)))
    np.testing.assert_allclose(corr(stats.posterior_covariance), corr(reference), atol=1e-5)


def test_noisy_range_rate_recovery_is_consistent_with_the_posterior():
    options = DMCOptions(sigma_mps2=1e-5, tau_s=1800.0)
    t, obs, geo, x9, guess = _dmc_arc(options, noise_seed=13)
    x, _, stats = _fit(t, obs, geo, guess, options, return_posterior=True)
    err = x - x9
    assert float(err @ np.linalg.solve(stats.posterior_covariance, err)) < 27.88   # chi-square(9) 99.9 %


def test_unsupported_range_rate_inputs_rejected():
    options = DMCOptions(sigma_mps2=1e-5, tau_s=1800.0)
    t, obs, geo, _, guess = _dmc_arc(options, duration_s=361.0)
    counted = replace(geo, range_rate_physics=RangeRatePhysicsConfig(mode="two_way_counted_doppler"))
    with pytest.raises(ValueError):
        _fit(t, obs, counted, guess, options)
    with pytest.raises(ValueError):                      # range-rate geometry into the position fit
        estimate_position_dmc_batch(t, obs, guess, geo, MU_MOON, 0.0, 0.0, _earth, _sun, options, **TOL)
