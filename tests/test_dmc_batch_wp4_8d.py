"""WP4.8d (EST-21): batch least squares with dynamic model compensation.

Before WP4.8d only the sequential filters carried the Gauss-Markov empirical
acceleration; BLS-LM and SRIF could not, so a batch-vs-filter comparison on an arc with
unmodelled forces compared different models.  Oracles: observations generated by the
DMC dynamics themselves (the fit must recover r0, v0, w0), a central-difference design
matrix (independent of the STM) for the posterior covariance, the agreement of the
normal-equation and QR solves, and the plain BLS-LM fit when w0 is pinned at zero.
"""
from __future__ import annotations

import numpy as np
import pytest

from lunar_od.dmc import DMCOptions, propagate_dmc_state
from lunar_od.dmc_batch import estimate_position_dmc_batch
from lunar_od.estimators import _position_residual_from_h, _position_weight_diagonal, estimate_position_bls_lm
from lunar_od.measurements import compute_position_residuals_analytic
from tests.test_ekf_smoother import MU_MOON, _add_noise, _arc, _earth, _sun
from tests.test_filters import _build_clean_position_observations

TOL = dict(rtol=1e-12, atol=1e-13)
W_TRUE = np.array([3e-6, -2e-6, 1e-6])


def _dmc_arc(options, noise_seed=None, duration_s=3601.0):
    x_true0, t_pass, _, pass_geo, _ = _arc("position", duration_s=duration_s)
    x9 = np.concatenate([x_true0, W_TRUE])
    truth = propagate_dmc_state(t_pass, x9, options, MU_MOON, 0.0, 0.0, _earth, _sun, stm=False, **TOL)
    obs = _build_clean_position_observations(t_pass, truth[:, :6], pass_geo)
    if noise_seed is not None:
        obs = _add_noise(obs, "position", np.random.default_rng(noise_seed))
    guess = np.concatenate([x_true0 + np.array([150.0, -80.0, 60.0, 0.05, -0.03, 0.02]), np.zeros(3)])
    return t_pass, obs, pass_geo, x9, guess


def _fit(t, obs, geo, guess, options, **kw):
    return estimate_position_dmc_batch(t, obs, guess, geo, MU_MOON, 0.0, 0.0, _earth, _sun, options, **TOL, **kw)


@pytest.mark.parametrize("axes", ["inertial", "rtn"])
def test_noiseless_dmc_truth_is_recovered(axes):
    """Weak w0 prior (sigma 1e-3 m/s^2, 300x the signal): the MAP pull towards w0 = 0 is
    (sigma_post / sigma)^2 of w, far below the tolerance."""
    options = DMCOptions(sigma_mps2=1e-3, tau_s=1800.0, axes=axes)
    t, obs, geo, x9, guess = _dmc_arc(options)
    x, status, _ = _fit(t, obs, geo, guess, options)
    assert status in {"Converged", "J-Stab"}
    assert np.linalg.norm(x[:3] - x9[:3]) < 1e-3
    assert np.linalg.norm(x[3:6] - x9[3:6]) < 1e-6
    np.testing.assert_allclose(x[6:], x9[6:], rtol=1e-3, atol=1e-11)


def test_normal_and_square_root_solves_agree():
    options = DMCOptions(sigma_mps2=1e-5, tau_s=1800.0, axes="rtn")
    t, obs, geo, _, guess = _dmc_arc(options, noise_seed=11)
    a, sa, stats = _fit(t, obs, geo, guess, options, return_posterior=True)
    b, sb, _ = _fit(t, obs, geo, guess, options, method="square_root")
    sigma = np.sqrt(np.diag(stats.posterior_covariance))
    assert sa in {"Converged", "J-Stab"} and sb in {"Converged", "J-Stab"}
    assert np.max(np.abs(a - b) / sigma) < 1e-3


def test_posterior_matches_a_finite_difference_design():
    options = DMCOptions(sigma_mps2=1e-5, tau_s=1800.0)
    t, obs, geo, _, guess = _dmc_arc(options, noise_seed=12)
    x, _, stats = _fit(t, obs, geo, guess, options, return_posterior=True)
    w = _position_weight_diagonal(obs, geo)

    def residual(xx):
        hist = propagate_dmc_state(t, xx, options, MU_MOON, 0.0, 0.0, _earth, _sun, stm=False, **TOL)
        _, h_nom, _ = compute_position_residuals_analytic(hist[:, :6], obs, geo)
        return _position_residual_from_h(obs, h_nom)

    # w enters almost linearly, so its step can be large; at 1e-9 m/s^2 the FD column was
    # roundoff-limited (2e-3), at 1e-7 the FD and STM posteriors agree to 8.7e-7
    steps = [1.0] * 3 + [1e-3] * 3 + [1e-7] * 3
    h = np.column_stack([-(residual(x + np.eye(9)[j] * s) - residual(x - np.eye(9)[j] * s)) / (2 * s)
                         for j, s in enumerate(steps)])
    prior = np.zeros((9, 9))
    prior[6:, 6:] = np.eye(3) / options.sigma_mps2**2
    d = np.sqrt(np.diag(h.T @ (w[:, None] * h) + prior))
    info_eq = (h.T @ (w[:, None] * h) + prior) / d[:, None] / d[None, :]
    reference = np.linalg.inv(info_eq) / d[:, None] / d[None, :]
    np.testing.assert_allclose(np.sqrt(np.diag(stats.posterior_covariance)), np.sqrt(np.diag(reference)), rtol=1e-5)
    corr = lambda c: c / np.sqrt(np.outer(np.diag(c), np.diag(c)))
    np.testing.assert_allclose(corr(stats.posterior_covariance), corr(reference), atol=1e-5)


def test_noisy_recovery_is_consistent_with_the_posterior():
    options = DMCOptions(sigma_mps2=1e-5, tau_s=1800.0)
    t, obs, geo, x9, guess = _dmc_arc(options, noise_seed=13)
    x, _, stats = _fit(t, obs, geo, guess, options, return_posterior=True)
    err = x - x9
    nees = float(err @ np.linalg.solve(stats.posterior_covariance, err))
    assert nees < 27.88                          # chi-square(9) 99.9 %


def test_pinned_w0_reproduces_the_plain_batch_fit():
    options = DMCOptions(sigma_mps2=1e-15, tau_s=1800.0)
    x_true0, t, _, geo, clean = _arc("position", duration_s=1801.0)
    obs = _add_noise(clean, "position", np.random.default_rng(14))
    guess6 = x_true0 + np.array([150.0, -80.0, 60.0, 0.05, -0.03, 0.02])
    plain, _, _ = estimate_position_bls_lm(t, obs, guess6, geo, MU_MOON, 0.0, 0.0, _earth, _sun, **TOL)
    x, status, _ = _fit(t, obs, geo, np.concatenate([guess6, np.zeros(3)]), options)
    assert status in {"Converged", "J-Stab"}
    # DOP853 (DMC) vs the production propagator: test_dmc bounds that gap at 1e-3 m
    assert np.linalg.norm(x[:3] - plain[:3]) < 1e-3
    assert np.linalg.norm(x[3:6] - plain[3:6]) < 1e-6


def test_invalid_inputs_rejected():
    options = DMCOptions(sigma_mps2=1e-5, tau_s=1800.0)
    t, obs, geo, _, guess = _dmc_arc(options, duration_s=361.0)
    with pytest.raises(ValueError):
        _fit(t, obs, geo, guess[:6], options)
    with pytest.raises(ValueError):
        _fit(t, obs, geo, guess, options, method="cholesky")
    with pytest.raises(ValueError):
        _fit(t, obs, geo, guess, DMCOptions(0.0, 1800.0))
