"""Ordinary Python cache creation must not invalidate portable source identities."""
import os
import subprocess
import sys

from tools.build_windows_portable import bundle_files, bundle_hashes


def test_actual_import_cache_is_excluded_but_changed_source_is_detected(tmp_path):
    module = tmp_path / "portable_probe.py"
    module.write_text("VALUE = 42\n", encoding="utf-8")
    before = bundle_hashes(tmp_path)
    env = os.environ.copy()
    env.pop("PYTHONDONTWRITEBYTECODE", None)
    subprocess.run([sys.executable, "-E", "-c",
                    "import portable_probe; assert portable_probe.VALUE == 42"],
                   cwd=tmp_path, env=env, check=True)
    assert list((tmp_path / "__pycache__").glob("*.pyc")), "Oracle requires actual generated bytecode"
    assert bundle_hashes(tmp_path) == before
    assert {p.name for p in bundle_files(tmp_path)} == {"portable_probe.py"}
    module.write_text("VALUE = 43\n", encoding="utf-8")
    assert bundle_hashes(tmp_path)["portable_probe.py"] != before["portable_probe.py"]
