"""Publish small, traceable tutorial outputs and a recorded visibility fixture.

Run explicitly: python tools/build_showcase.py --run outputs/quickstart
Existing scientific study records are never regenerated by this script.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import shutil

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def build(run_dir):
    destination = ROOT / "docs/figures/quickstart"
    destination.mkdir(parents=True, exist_ok=True)
    summary = json.loads((run_dir / "summary.json").read_text())
    if summary["source"]["git_dirty"] is not False:
        raise ValueError("Publish from a clean committed source checkout with known Git identity")
    for name, digest in summary["artifact_sha256"].items():
        path = run_dir / name
        if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise ValueError(f"Tutorial output changed: {name}")
        shutil.copy2(path, destination / name)
    shutil.copy2(run_dir / "summary.json", destination / "summary.json")

    fixture = ROOT / "fixtures/spice_snapshots.json"
    data = json.loads(fixture.read_text())
    visibility = data["visibility"]
    times = np.asarray(visibility["t_eval_s"], dtype=float)
    mask = np.asarray(visibility["multi_vis_mask_raw"], dtype=bool)
    names = visibility["multi_station_names"]
    # Plot the actual sampled fixture, without inventing between-sample access.
    fig, ax = plt.subplots(figsize=(8.6, 3.8), constrained_layout=True)
    for index, name in enumerate(names):
        ax.scatter(times / 60, np.full(times.size, index), marker="x", color="#aaaaaa", s=35)
        ax.scatter(times[mask[:, index]] / 60, np.full(mask[:, index].sum(), index),
                   marker="s", color="#012855", s=60,
                   label="Recorded visible sample" if index == 0 else None)
    # The legend is explicit even if the first station has no visible samples.
    ax.set(yticks=range(len(names)), yticklabels=names, xlabel="Elapsed time (min)",
           title="Station visibility · six recorded fixture epochs")
    ax.scatter([], [], marker="x", color="#aaaaaa", label="Recorded not visible")
    ax.legend(loc="upper right", fontsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    for extension in ("png", "svg"):
        fig.savefig(destination / f"fixture-visibility.{extension}", dpi=300, bbox_inches="tight")
    plt.close(fig)
    record = {
        "source": "fixtures/spice_snapshots.json", "source_sha256": hashlib.sha256(fixture.read_bytes()).hexdigest(),
        "data_keys": ["visibility.t_eval_s", "visibility.multi_vis_mask_raw", "visibility.multi_station_names"],
        "sample_count": len(times), "epoch_utc": data["epoch_utc"],
        "minimum_elevation_deg": visibility["min_elevation_deg"],
        "interpretation": "Recorded fixture samples only; separate from the idealized quickstart arc; not continuous access intervals",
        "producing_script": "tools/build_showcase.py",
        "producing_script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "source_commit": summary["source"]["git_commit"],
    }
    (destination / "visibility-source.json").write_text(json.dumps(record, indent=2) + "\n")
    print(f"Published verified tutorial artifacts and fixture samples to {destination}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, default=Path("outputs/quickstart"))
    build(parser.parse_args().run)
