"""Phase C2-I: generate src/lunar_od/_erfa_dtdb_table.py from ERFA's dtdb.c.

Predeclared in studies/phase17/configs/phase_c2i_station_time_implementation_predeclaration.json
(architecture.series_source): the coefficient table is generated from the C source, never typed by hand.

Source: liberfa/erfa/src/dtdb.c and liberfa/erfa/LICENSE inside the pyerfa 2.0.1.5 sdist
(pyerfa-2.0.1.5.tar.gz, sha256 17d6b24fe4846c65d5e7d8c362dcb08199dc63b30a236aedd73875cc83e1f6c0, from PyPI),
which carries ERFA 2.0.1. Every number is copied as its decimal token; Python's float() and a C compiler
both round a decimal literal correctly, so the doubles are the same.

    python studies/phase17/scripts/phase_c2i_generate_dtdb_table.py <dtdb.c> <LICENSE> [<output.py>]
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

DTDB_C_SHA256 = "228bd7c7c1c88dda44c29a076f289c968f64d77a2dc389138b03ab5d1d442105"
SDIST = "pyerfa-2.0.1.5.tar.gz"
SDIST_SHA256 = "17d6b24fe4846c65d5e7d8c362dcb08199dc63b30a236aedd73875cc83e1f6c0"
OUT = Path(__file__).resolve().parents[3] / "src" / "lunar_od" / "_erfa_dtdb_table.py"

NUM = r"[-+]?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?"
EXPECTED_GROUPS = ((0, 473), (474, 678), (679, 763), (764, 783), (784, 786))
ARGS = ("tsol", "elsun", "emsun", "d", "elj", "els")


def _between(text: str, start: str, end: str) -> str:
    i = text.index(start)
    return text[i + len(start):text.index(end, i)]


def parse(c: str) -> dict:
    body = _between(c, "fairhd[787][3] = {", "};")
    rows = re.findall(rf"\{{\s*({NUM}),\s*({NUM}),\s*({NUM})\s*\}}", body)
    if len(rows) != 787:
        raise ValueError(f"fairhd: {len(rows)} rows, expected 787")

    loops = re.findall(r"for \(j = (\d+); j >= (\d+); j--\)", c)
    groups = tuple(sorted((int(lo), int(hi)) for hi, lo in loops))
    if groups != EXPECTED_GROUPS:
        raise ValueError(f"term groups {groups} != {EXPECTED_GROUPS}")
    if "wf = t * (t * (t * (t * w4 + w3) + w2) + w1) + w0;" not in c:
        raise ValueError("unexpected power-series combination")

    fundamental = {}
    for name in ARGS[1:]:
        m = re.search(rf"\b{name} = fmod\(({NUM}) \+ ({NUM}) \* w, 360\.0\) \* ERFA_DD2R;", c)
        if not m:
            raise ValueError(f"fundamental argument {name} not found")
        fundamental[name] = (m.group(1), m.group(2))

    wt_block = _between(c, "wt =", ";")
    topo = []
    for sign, coef, uv, fn, arg in re.findall(
            rf"([+-])\s*({NUM})\s*\*\s*([uv])\s*\*\s*(sin|cos)\(([^)]*)\)", wt_block):
        mult = {}
        for s2, k, name in re.findall(r"([+-]?)\s*(?:(\d+\.\d*)\s*\*\s*)?(tsol|elsun|emsun|elj|els|d)\b", arg):
            mult[name] = mult.get(name, 0.0) + (-1.0 if s2 == "-" else 1.0) * (float(k) if k else 1.0)
        topo.append((("-" if sign == "-" else "") + coef, uv, fn, tuple((n, mult[n]) for n in ARGS if n in mult)))
    if len(topo) != 10:
        raise ValueError(f"topocentric terms: {len(topo)}, expected 10")

    wj_block = _between(c, "wj =", ";")
    jpl = re.findall(rf"\(?\s*({NUM})\s*\*\s*sin\(\s*({NUM})\s*\*\s*t\s*\+\s*({NUM})\)\)?", wj_block)
    jpl_t2 = re.findall(rf"({NUM})\s*\*\s*t\s*\*\s*t", wj_block)
    if len(jpl) != 4 or len(jpl_t2) != 1:
        raise ValueError("JPL mass adjustment terms not as expected")
    if "w = wt + wf + wj;" not in c:
        raise ValueError("unexpected final combination")
    return dict(rows=rows, groups=groups, fundamental=fundamental, topo=topo, jpl=jpl, jpl_t2=jpl_t2[0])


def render(p: dict, licence: str) -> str:
    lic = "\n".join(("# " + ln).rstrip() for ln in licence.strip().splitlines())
    out = [
        '"""Coefficients of ERFA eraDtdb (TDB - TT, Fairhead & Bretagnon 1990 + topocentric terms).',
        "",
        "GENERATED by studies/phase17/scripts/phase_c2i_generate_dtdb_table.py - do not edit by hand.",
        f"Source: ERFA 2.0.1 liberfa/erfa/src/dtdb.c (sha256 {DTDB_C_SHA256})",
        f"from {SDIST} (sha256 {SDIST_SHA256}). Licence of the source below.",
        '"""',
        lic,
        "",
        f'SOURCE_SHA256 = "{DTDB_C_SHA256}"',
        "",
        "#: (amplitude [s], frequency [rad / Julian millennium], phase [rad]), dtdb.c order",
        "FAIRHD = (",
    ]
    out += [f"    ({a}, {f}, {ph})," for a, f, ph in p["rows"]]
    out += [")", "", "#: index ranges (inclusive) of the T**0 .. T**4 groups", f"GROUPS = {p['groups']!r}", "",
            "#: fundamental arguments: angle = fmod(c0 + c1 * t_millennia / 3600, 360) deg",
            "FUNDAMENTAL = {"]
    out += [f'    "{k}": ({c0}, {c1}),' for k, (c0, c1) in p["fundamental"].items()]
    out += ["}", "", "#: topocentric terms: (coefficient [s/km], 'u' | 'v', 'sin' | 'cos', ((argument, multiplier), ...))",
            "TOPOCENTRIC = ("]
    out += [f"    ({coef}, {uv!r}, {fn!r}, {mult!r})," for coef, uv, fn, mult in p["topo"]]
    out += [")", "", "#: JPL-mass adjustment: (amplitude [s], frequency, phase), plus amplitude x t**2",
            "JPL = ("]
    out += [f"    ({a}, {f}, {ph})," for a, f, ph in p["jpl"]]
    out += [")", f"JPL_T2 = {p['jpl_t2']}", ""]
    return "\n".join(out)


def main():
    c_path, lic_path = Path(sys.argv[1]), Path(sys.argv[2])
    out = Path(sys.argv[3]) if len(sys.argv) > 3 else OUT
    data = c_path.read_bytes()
    sha = hashlib.sha256(data).hexdigest()
    if sha != DTDB_C_SHA256:
        raise SystemExit(f"dtdb.c sha256 {sha} != pinned {DTDB_C_SHA256}")
    p = parse(data.decode("ascii"))
    out.write_text(render(p, lic_path.read_text(encoding="utf-8")), encoding="utf-8", newline="\n")
    print(f"wrote {out}: {len(p['rows'])} terms, groups {p['groups']}, {len(p['topo'])} topocentric, "
          f"{len(p['jpl'])} JPL; sha256 {hashlib.sha256(out.read_bytes()).hexdigest()}")


if __name__ == "__main__":
    main()
